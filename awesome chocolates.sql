-- =========================================================
-- 7. SALESPERSON ANALYSIS
-- =========================================================


-- 16. Find the total sales generated by each salesperson.

SELECT
    p.salesperson,
    SUM(s.amount) AS total_sales
FROM sales s
JOIN people p
    ON s.SPID = p.SPID
GROUP BY p.salesperson;


-- 17. Find the top 5 best-performing salespersons
--     based on sales amount.

SELECT
    p.salesperson,
    SUM(s.amount) AS sales_amount
FROM sales s
JOIN people p
    ON s.SPID = p.SPID
GROUP BY p.salesperson
ORDER BY sales_amount DESC
LIMIT 5;


-- 18. Find the total boxes sold by each salesperson.

SELECT
    p.salesperson,
    SUM(s.boxes) AS total_boxes
FROM sales s
JOIN people p
    ON s.SPID = p.SPID
GROUP BY p.salesperson;


-- =========================================================
-- 8. WHERE + GROUP BY + HAVING
-- =========================================================


-- 19. Find each product's total sales,
--     considering only transactions where
--     Amount > 1,000 OR Customers > 20,
--     and sort highest first.

SELECT
    PID,
    SUM(amount) AS total_sales
FROM sales
WHERE amount > 1000
   OR customers > 20
GROUP BY PID
ORDER BY total_sales DESC;


-- 20. Find each salesperson's average sales amount,
--     considering only transactions where
--     Amount > 1,000 AND Boxes > 10,
--     and display the top 5.

SELECT
    p.salesperson,
    AVG(s.amount) AS average_sales_amount,
    SUM(s.boxes) AS total_boxes
FROM sales s
JOIN people p
    ON s.SPID = p.SPID
WHERE s.amount > 1000
  AND s.boxes > 10
GROUP BY p.salesperson
ORDER BY average_sales_amount DESC
LIMIT 5;


